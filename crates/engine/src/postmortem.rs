//! HOR-26 — Deterministic incident postmortem generator. Turns a completed
//! InvestigationReport into a DRAFT postmortem document. Pure Markdown, no AI, no I/O.

use crate::js::to_fixed;
use crate::render::{role_name, short_id};
use crate::types::{evidence_kind_name, provider_kind_name, InvestigationReport};
use crate::validate::Verdict;
use horus_core::EvidenceKind;
use indexmap::IndexSet;
use regex::Regex;
use std::sync::LazyLock;

pub struct GroundingCheck {
    pub valid: bool,
    pub unknown_ids: Vec<String>,
}

static BACKTICK_RE: LazyLock<Regex> = LazyLock::new(|| Regex::new(r"`([a-zA-Z0-9_\-]{8})`").unwrap());
static LIST_RE: LazyLock<Regex> = LazyLock::new(|| Regex::new(r"(?m)^- ([a-zA-Z0-9_\-]{8}) \[").unwrap());

/// Verify that every evidence short-ID cited in a generated postmortem text maps back to an
/// evidence item in the source report. Any unknown ID signals tampering or a bug.
pub fn validate_postmortem_grounding(r: &InvestigationReport, postmortem_text: &str) -> GroundingCheck {
    let known: std::collections::HashSet<String> = r.evidence.iter().map(|e| short_id(&e.id)).collect();
    let mut cited: IndexSet<String> = IndexSet::new();
    for m in BACKTICK_RE.captures_iter(postmortem_text) {
        cited.insert(m[1].to_string());
    }
    for m in LIST_RE.captures_iter(postmortem_text) {
        cited.insert(m[1].to_string());
    }
    let unknown_ids: Vec<String> = cited.into_iter().filter(|id| !known.contains(id)).collect();
    GroundingCheck { valid: unknown_ids.is_empty(), unknown_ids }
}

/// Generate a deterministic DRAFT postmortem Markdown document from a completed report.
pub fn generate_postmortem(r: &InvestigationReport) -> String {
    let mut lines: Vec<String> = vec![];

    lines.push(format!("# Incident Postmortem — {}", r.input.hint));
    lines.push("".into());
    lines.push("_Draft generated by Horus — deterministic, no AI. Edit freely; Horus drafts, it does not dictate._".into());
    lines.push("".into());
    lines.push(format!("**Confidence:** {}", to_fixed(r.confidence, 2)));
    if let Some(s) = r.input.service.as_deref().filter(|s| !s.is_empty()) {
        lines.push(format!("**Service:** {s}"));
    }
    if let Some(s) = r.input.since.as_deref().filter(|s| !s.is_empty()) {
        lines.push(format!("**Since:** {s}"));
    }
    lines.push("".into());

    lines.push("## Summary".into());
    lines.push("".into());
    lines.push(r.summary.clone());
    lines.push("".into());

    lines.push("## Impact".into());
    lines.push("".into());

    let impact_evidence: Vec<_> = r.evidence.iter().filter(|e| e.kind == EvidenceKind::Impact).collect();
    let has_boundary_crossings = !r.timeline.boundary_crossings.is_empty();

    if !impact_evidence.is_empty() {
        lines.push("The following impact signals were observed:".into());
        lines.push("".into());
        for e in &impact_evidence {
            lines.push(format!("- `{}` {}", short_id(&e.id), e.title));
        }
        lines.push("".into());
    }

    if has_boundary_crossings {
        lines.push("Async boundaries crossed during the incident:".into());
        lines.push("".into());
        for bc in &r.timeline.boundary_crossings {
            lines.push(format!(
                "- **{}**: {} → {}",
                bc.queue_name,
                bc.producer.as_deref().unwrap_or("?"),
                bc.worker.as_deref().unwrap_or("?")
            ));
        }
        lines.push("".into());
    }

    if impact_evidence.is_empty() && !has_boundary_crossings {
        lines.push("_No impact evidence was captured during this investigation._".into());
        lines.push("".into());
    }

    // Find a metrics gap if present — cite it for the precision caveat
    match r.gap_analysis.gaps.iter().find(|g| g.dimension == "metrics") {
        Some(g) => lines.push(format!(
            "> **Note:** Precise user/runtime impact (error rates, latency percentiles, affected user count) requires metrics that were unavailable during this investigation. {} Next: {}.",
            g.why, g.next_source
        )),
        None => lines.push(
            "> **Note:** Confirm precise user/runtime impact (error rates, affected user count) with your metrics provider.".into(),
        ),
    }
    lines.push("".into());

    lines.push("## Timeline".into());
    lines.push("".into());
    if r.timeline.events.is_empty() {
        lines.push("_no timeline_".into());
    } else {
        for ev in &r.timeline.events {
            lines.push(format!("{}. [{}] {}", ev.order, ev.at.as_deref().unwrap_or("structural"), ev.title));
        }
    }
    lines.push("".into());

    lines.push("## Contributing factors".into());
    lines.push("".into());

    let supported: Vec<_> = r.hypotheses.iter().filter(|h| h.verdict == Verdict::Supported).collect();
    let commit_evidence: Vec<_> = r.evidence.iter().filter(|e| e.kind == EvidenceKind::Commit).collect();
    let chain_count = r.cause_chains.as_ref().map(|c| c.len()).unwrap_or(0);

    if supported.is_empty() && commit_evidence.is_empty() {
        match r.suspected_causes.first() {
            Some(top) => {
                lines.push("_No hypotheses reached 'supported' status. The leading suspected cause is unconfirmed:_".into());
                lines.push("".into());
                lines.push(format!("1. **(score {}, {})** {}", to_fixed(top.final_score, 2), top.band.as_str(), top.title));
            }
            None => lines.push("_No confirmed contributing factors were identified. Further evidence is needed._".into()),
        }
    } else {
        if chain_count > 0 {
            lines.push("The following causal sequences are supported by the collected evidence:".into());
            lines.push("".into());
            for chain in r.cause_chains.as_deref().unwrap_or(&[]) {
                lines.push(format!("### {} _(confidence {})_", chain.category, to_fixed(chain.confidence, 2)));
                lines.push("".into());
                lines.push(chain.summary.clone());
                lines.push("".into());
                for (i, step) in chain.steps.iter().enumerate() {
                    let ev_cite = if step.evidence_ids.is_empty() {
                        String::new()
                    } else {
                        format!(
                            " — evidence: {}",
                            step.evidence_ids.iter().map(|id| format!("`{}`", short_id(id))).collect::<Vec<_>>().join(", ")
                        )
                    };
                    lines.push(format!("{}. **[{}]** {}{ev_cite}", i + 1, role_name(step.role), step.label));
                }
                lines.push("".into());
            }
        } else if !supported.is_empty() {
            lines.push("The following factors are supported by the collected evidence:".into());
            lines.push("".into());
            for h in &supported {
                lines.push(format!("- **{}:** {} _(confidence {})_", h.category, h.statement, to_fixed(h.confidence, 2)));
            }
        }

        if !commit_evidence.is_empty() {
            if !supported.is_empty() || chain_count > 0 {
                lines.push("".into());
            }
            lines.push("Recent changes (commit evidence) present during this incident:".into());
            lines.push("".into());
            for e in &commit_evidence {
                lines.push(format!("- `{}` {}", short_id(&e.id), e.title));
            }
        }
    }
    lines.push("".into());

    lines.push("## Root cause (candidate)".into());
    lines.push("".into());

    let gap_dimensions = r.gap_analysis.gaps.iter().take(2).map(|g| g.dimension.as_str()).collect::<Vec<_>>().join(", ");
    let gap_caveat = if !gap_dimensions.is_empty() {
        format!("This candidate cannot be confirmed while evidence gaps remain (missing: {gap_dimensions}).")
    } else {
        "Review the gap analysis and gather additional evidence before confirming.".to_string()
    };

    if let Some(h) = supported.first() {
        lines.push(format!("**CANDIDATE** _(confidence {})_: {}", to_fixed(h.confidence, 2), h.statement));
        lines.push("".into());
        lines.push(format!("_{gap_caveat}_"));
    } else if let Some(c) = r.suspected_causes.first() {
        lines.push(format!(
            "**CANDIDATE** _(score {}, {}, unconfirmed)_: {}",
            to_fixed(c.final_score, 2),
            c.band.as_str(),
            c.title
        ));
        lines.push("".into());
        lines.push(format!("_{gap_caveat}_"));
    } else {
        lines.push("_No candidate root cause could be determined from the available evidence._".into());
        lines.push("".into());
        lines.push(format!("_{gap_caveat}_"));
    }
    lines.push("".into());

    lines.push("## Evidence".into());
    lines.push("".into());
    if r.evidence.is_empty() {
        lines.push("_No evidence was collected._".into());
    } else {
        for e in &r.evidence {
            lines.push(format!("- {} [{}/{}] {}", short_id(&e.id), provider_kind_name(e.source), evidence_kind_name(e.kind), e.title));
        }
    }
    lines.push("".into());

    lines.push("## Lessons learned".into());
    lines.push("".into());
    if r.gap_analysis.gaps.is_empty() {
        lines.push("Good observability coverage for this investigation. Consider reviewing your alerting and on-call runbooks to ensure similar incidents are detected and scoped faster in future.".into());
    } else {
        for gap in &r.gap_analysis.gaps {
            lines.push(format!(
                "- During this incident, **{}** was unavailable — {} Wiring **{}** would let the next investigation confirm or rule this out faster.",
                gap.dimension, gap.why, gap.next_source
            ));
        }
    }
    lines.push("".into());

    lines.push("## Follow-up actions".into());
    lines.push("".into());

    // Merge structural next actions with gap-based actions so connector follow-ups appear once,
    // tied to the dimension they close.
    let mut checkbox_items: Vec<String> = vec![];
    let mut seen: std::collections::HashSet<String> = std::collections::HashSet::new();
    for action in &r.next_actions {
        if seen.insert(action.clone()) {
            checkbox_items.push(action.clone());
        }
    }
    let mut seen_gap_sources: std::collections::HashSet<&str> = std::collections::HashSet::new();
    for gap in &r.gap_analysis.gaps {
        if !seen_gap_sources.insert(gap.next_source.as_str()) {
            continue;
        }
        let clean = format!("{} to close the '{}' evidence gap", gap.next_source, gap.dimension);
        if seen.contains(&gap.next_source) {
            if let Some(idx) = checkbox_items.iter().position(|i| *i == gap.next_source) {
                if !seen.contains(&clean) {
                    checkbox_items[idx] = clean.clone();
                    seen.remove(&gap.next_source);
                    seen.insert(clean);
                }
            }
        } else if !seen.contains(&clean) {
            seen.insert(clean.clone());
            checkbox_items.push(clean);
        }
    }

    if checkbox_items.is_empty() {
        lines.push("- [ ] Review this postmortem with the team and decide on follow-ups.".into());
    } else {
        for item in &checkbox_items {
            lines.push(format!("- [ ] {item}"));
        }
    }
    lines.push("".into());

    lines.join("\n")
}
